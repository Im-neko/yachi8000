/**
 * VRM ファイルを読む（F-20, F-62）。
 *
 * **置き場所は設定ファイルと同じ PVC**（→ D-36 の 2）。パスは設定ファイル
 * から来るもので、リクエストからは来ない —— 受けたパスをそのまま読むと、
 * 読み上げのために開けた口がファイルシステム全体の覗き穴になる。
 */
export interface ModelFileReader {
  /**
   * 読んで返す。**置かれていなければ undefined。**
   *
   * 「まだ置いていない」は運用の途中経過なので undefined で返し、呼び出し側
   * がそう伝える。**それ以外の失敗（権限が無い・壊れている）は投げる** ——
   * 同じ扱いにすると、置き忘れと壊れたファイルの区別が付かなくなる。
   */
  read(path: string): Promise<Uint8Array | undefined>;
}
